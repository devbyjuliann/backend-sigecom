CREATE TABLE IF NOT EXISTS purchase_orders (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  supplier_id BIGINT UNSIGNED NOT NULL,
  warehouse_id BIGINT UNSIGNED NOT NULL,
  order_date DATE NOT NULL,
  reference VARCHAR(120) NULL,
  notes VARCHAR(1000) NULL,
  status ENUM('draft', 'confirmed', 'cancelled') NOT NULL DEFAULT 'draft',
  version BIGINT UNSIGNED NOT NULL DEFAULT 1,
  created_by BIGINT UNSIGNED NOT NULL,
  updated_by BIGINT UNSIGNED NOT NULL,
  confirmed_by BIGINT UNSIGNED NULL,
  confirmed_at DATETIME(3) NULL,
  cancelled_by BIGINT UNSIGNED NULL,
  cancelled_at DATETIME(3) NULL,
  cancellation_reason VARCHAR(500) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_purchase_orders_warehouse_status_date (warehouse_id, status, order_date, id),
  KEY idx_purchase_orders_supplier_date (supplier_id, order_date, id),
  KEY idx_purchase_orders_created (created_at, id),
  CONSTRAINT fk_purchase_orders_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id) ON DELETE RESTRICT,
  CONSTRAINT fk_purchase_orders_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouses (id) ON DELETE RESTRICT,
  CONSTRAINT fk_purchase_orders_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
  CONSTRAINT fk_purchase_orders_updated_by FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE RESTRICT,
  CONSTRAINT fk_purchase_orders_confirmed_by FOREIGN KEY (confirmed_by) REFERENCES users (id) ON DELETE RESTRICT,
  CONSTRAINT fk_purchase_orders_cancelled_by FOREIGN KEY (cancelled_by) REFERENCES users (id) ON DELETE RESTRICT,
  CONSTRAINT chk_purchase_orders_version CHECK (version > 0),
  CONSTRAINT chk_purchase_orders_confirmation CHECK ((status = 'draft' AND confirmed_at IS NULL AND confirmed_by IS NULL) OR (status = 'confirmed' AND confirmed_at IS NOT NULL AND confirmed_by IS NOT NULL) OR (status = 'cancelled' AND ((confirmed_at IS NULL AND confirmed_by IS NULL) OR (confirmed_at IS NOT NULL AND confirmed_by IS NOT NULL)))),
  CONSTRAINT chk_purchase_orders_cancellation CHECK ((status = 'cancelled' AND cancelled_at IS NOT NULL AND cancelled_by IS NOT NULL AND cancellation_reason IS NOT NULL) OR (status <> 'cancelled' AND cancelled_at IS NULL AND cancelled_by IS NULL AND cancellation_reason IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS purchase_order_lines (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  purchase_order_id BIGINT UNSIGNED NOT NULL,
  product_id BIGINT UNSIGNED NOT NULL,
  position SMALLINT UNSIGNED NOT NULL,
  sku_snapshot VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  name_snapshot VARCHAR(160) NOT NULL,
  unit_snapshot VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  quantity INT UNSIGNED NOT NULL,
  unit_cost DECIMAL(15,2) NOT NULL,
  line_total DECIMAL(22,2) NOT NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_purchase_order_lines_id_order (id, purchase_order_id),
  UNIQUE KEY uq_purchase_order_lines_product (purchase_order_id, product_id),
  KEY idx_purchase_order_lines_order (purchase_order_id, is_active, position),
  CONSTRAINT fk_purchase_order_lines_order FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders (id) ON DELETE RESTRICT,
  CONSTRAINT fk_purchase_order_lines_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
  CONSTRAINT chk_purchase_order_lines_quantity CHECK (quantity > 0),
  CONSTRAINT chk_purchase_order_lines_cost CHECK (unit_cost >= 0 AND line_total >= 0),
  CONSTRAINT chk_purchase_order_lines_unit CHECK (unit_snapshot IN ('unidad', 'caja', 'paquete', 'docena', 'display', 'bulto', 'par'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS purchase_receipts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  purchase_order_id BIGINT UNSIGNED NOT NULL,
  reference VARCHAR(120) NOT NULL,
  notes VARCHAR(1000) NULL,
  source_operation_id BIGINT UNSIGNED NULL,
  idempotency_key VARCHAR(128) NULL,
  request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  received_by BIGINT UNSIGNED NOT NULL,
  received_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_purchase_receipts_order_reference (purchase_order_id, reference),
  UNIQUE KEY uq_purchase_receipts_operation (source_operation_id),
  UNIQUE KEY uq_purchase_receipts_actor_key (received_by, idempotency_key),
  KEY idx_purchase_receipts_order_received (purchase_order_id, received_at, id),
  CONSTRAINT fk_purchase_receipts_order FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders (id) ON DELETE RESTRICT,
  CONSTRAINT fk_purchase_receipts_operation FOREIGN KEY (source_operation_id) REFERENCES inventory_operations (id) ON DELETE RESTRICT,
  CONSTRAINT fk_purchase_receipts_user FOREIGN KEY (received_by) REFERENCES users (id) ON DELETE RESTRICT,
  CONSTRAINT chk_purchase_receipts_reference CHECK (CHAR_LENGTH(TRIM(reference)) > 0),
  CONSTRAINT chk_purchase_receipts_idempotency CHECK ((idempotency_key IS NULL AND request_hash IS NULL) OR (idempotency_key IS NOT NULL AND request_hash IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS purchase_receipt_lines (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  purchase_receipt_id BIGINT UNSIGNED NOT NULL,
  purchase_order_id BIGINT UNSIGNED NOT NULL,
  purchase_order_line_id BIGINT UNSIGNED NOT NULL,
  quantity INT UNSIGNED NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_purchase_receipt_lines_receipt_order_line (purchase_receipt_id, purchase_order_id, purchase_order_line_id),
  KEY idx_purchase_receipt_lines_order_line (purchase_order_id, purchase_order_line_id),
  CONSTRAINT fk_purchase_receipt_lines_receipt FOREIGN KEY (purchase_receipt_id) REFERENCES purchase_receipts (id) ON DELETE RESTRICT,
  CONSTRAINT fk_purchase_receipt_lines_order_line FOREIGN KEY (purchase_order_line_id, purchase_order_id) REFERENCES purchase_order_lines (id, purchase_order_id) ON DELETE RESTRICT,
  CONSTRAINT chk_purchase_receipt_lines_quantity CHECK (quantity > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
